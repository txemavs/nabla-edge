    echo ""
  fi
}

# --- Main ---

MODE="button"
SATELLITE_NAME="$(hostname -s 2>/dev/null || echo 'edge')"
GPIO_PIN=17

while [ $# -gt 0 ]; do
  case "$1" in
    --mode)
      MODE="$2"
      shift 2
      ;;
    --port)
      SATELLITE_PORT="$2"
      shift 2
      ;;
    --name)
      SATELLITE_NAME="$2"
      shift 2
      ;;
    --help|-h)
      usage
      ;;
    *)
      err "Unknown option: $1"
      usage
      ;;
  esac
done

# Validate mode
case "$MODE" in
  button|wake) ;;
  *)
    err "Invalid mode: $MODE (use button or wake)"
    exit 1
    ;;
esac

check_root

log "Installing Wyoming satellite (mode=$MODE)..."

install_system_deps
create_venv
create_config
install_helper_scripts
create_systemd_service
enable_services
print_next_steps
